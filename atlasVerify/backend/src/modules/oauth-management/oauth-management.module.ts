import { Module } from '@nestjs/common';
import { BullModule } from '@nestjs/bullmq';
import { DatabaseModule } from '@database/database.module';
import { QUEUE_NAMES } from '@common/constants';
import { RolesPermissionsModule } from '@modules/roles-permissions/roles-permissions.module';
import { AuditLogsModule } from '@modules/audit-logs/audit-logs.module';
import { TenantIsolationModule } from '@modules/tenant-isolation/tenant-isolation.module';
import { OAuthManagementController } from './oauth-management.controller';
import { OAuthManagementService } from './oauth-management.service';
import { OAuthManagementRepository } from './oauth-management.repository';
import { OAuthCredentialEncryptor } from './oauth-credential.encryptor';
import { OAuthCredentialDecryptor } from './oauth-credential.decryptor';
import { OAuthManagementEventQueue, OAuthManagementEventWorker } from './jobs';

/**
 * OAuthManagementModule — generic OAuth client/connection management for
 * ATLAS *integrating out* to external providers (authorization-code and
 * client-credentials grants), distinct from ATLAS's own JWT-based user
 * login (`authentication` module) and from API Key Management (inbound,
 * ATLAS-issued keys for programmatic callers). Provider-specific behavior
 * is intentionally NOT hardcoded here — `OAuthClient` stores admin-configured
 * authorization/token/revocation/userinfo endpoints so future per-provider
 * adapters can layer on top without this module knowing about any one
 * provider. Client secrets and access/refresh token references are
 * AES-256-GCM encrypted and are never returned in plaintext once stored —
 * `clientSecret`/token values that come IN via DTOs are always provider- or
 * exchange-issued, never generated by ATLAS.
 */
@Module({
  imports: [
    DatabaseModule,
    RolesPermissionsModule,
    AuditLogsModule,
    TenantIsolationModule,
    BullModule.registerQueue({
      name: QUEUE_NAMES.OAUTH_MANAGEMENT_EVENTS,
    }),
  ],
  controllers: [OAuthManagementController],
  providers: [
    OAuthManagementService,
    OAuthManagementRepository,
    OAuthCredentialEncryptor,
    OAuthCredentialDecryptor,
    OAuthManagementEventQueue,
    OAuthManagementEventWorker,
  ],
  exports: [OAuthManagementService],
})
export class OAuthManagementModule {}
