import { ArrayMinSize, IsArray, IsBoolean, IsEnum, IsNotEmpty, IsOptional, IsString } from 'class-validator';
import { SsoProtocol, SsoScopeType } from '../interfaces';

export class RegisterSsoConnectionDto {
  @IsString()
  @IsNotEmpty()
  name: string;

  @IsString()
  @IsOptional()
  description?: string;

  @IsEnum(SsoScopeType)
  scopeType: SsoScopeType;

  /** Required for ORGANIZATION scope. */
  @IsString()
  @IsOptional()
  organizationId?: string;

  @IsEnum(SsoProtocol)
  protocol: SsoProtocol;

  @IsArray()
  @IsString({ each: true })
  @ArrayMinSize(1)
  domains: string[];

  @IsArray()
  @IsString({ each: true })
  @IsOptional()
  scopes?: string[];

  @IsString()
  @IsOptional()
  issuer?: string;

  /** SAML: the IdP's entity ID. */
  @IsString()
  @IsOptional()
  entityId?: string;

  /** OIDC: the client ID as issued by the IdP. */
  @IsString()
  @IsOptional()
  clientId?: string;

  /** OIDC: the client secret as issued by the IdP — never generated by ATLAS. */
  @IsString()
  @IsOptional()
  clientSecret?: string;

  @IsString()
  @IsOptional()
  metadataUrl?: string;

  /** SAML: IdP SSO (login) redirect endpoint. */
  @IsString()
  @IsOptional()
  ssoUrl?: string;

  /** SAML: IdP single-logout endpoint. */
  @IsString()
  @IsOptional()
  sloUrl?: string;

  /** SAML: IdP signing certificate (PEM). */
  @IsString()
  @IsOptional()
  certificate?: string;

  @IsString()
  @IsOptional()
  authorizationEndpoint?: string;

  @IsString()
  @IsOptional()
  tokenEndpoint?: string;

  @IsString()
  @IsOptional()
  jwksUri?: string;

  @IsString()
  @IsOptional()
  userInfoEndpoint?: string;

  @IsString()
  @IsOptional()
  endSessionEndpoint?: string;

  @IsBoolean()
  @IsOptional()
  jitProvisioningEnabled?: boolean;

  @IsString()
  @IsOptional()
  groupClaimName?: string;

  /** `Role.id` (Roles & Permissions) to assign JIT-provisioned users with no matching group mapping. */
  @IsString()
  @IsOptional()
  defaultRoleId?: string;
}
