/**
 * AiCapability
 *
 * The set of generic capabilities an AI provider can declare support for.
 * Business modules request work by capability, never by provider name.
 */
export enum AiCapability {
  TEXT_GENERATION = 'TEXT_GENERATION',
  REASONING = 'REASONING',
  VISION = 'VISION',
  IMAGE_GENERATION = 'IMAGE_GENERATION',
  EMBEDDING = 'EMBEDDING',
  VALIDATION = 'VALIDATION',
  CLASSIFICATION = 'CLASSIFICATION',
  STRUCTURED_OUTPUT = 'STRUCTURED_OUTPUT',
}

/**
 * AiProviderLifecycleStatus
 *
 * Tracks a registered provider instance through its operational lifecycle.
 */
export enum AiProviderLifecycleStatus {
  UNINITIALIZED = 'UNINITIALIZED',
  INITIALIZING = 'INITIALIZING',
  READY = 'READY',
  DEGRADED = 'DEGRADED',
  UNAVAILABLE = 'UNAVAILABLE',
  DISABLED = 'DISABLED',
}

/**
 * AiProviderHealthStatus
 *
 * Point-in-time health assessment, independent of lifecycle status
 * (e.g. a READY provider can still report DEGRADED health).
 */
export enum AiProviderHealthStatus {
  HEALTHY = 'HEALTHY',
  DEGRADED = 'DEGRADED',
  UNHEALTHY = 'UNHEALTHY',
  UNKNOWN = 'UNKNOWN',
}

